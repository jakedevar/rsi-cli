pub const fn execution_route(purpose: ModelInvocationPurpose) -> ExecutionRoute {
    match purpose {
        ModelInvocationPurpose::SessionLaunchFresh
        | ModelInvocationPurpose::SessionContinueResume
        | ModelInvocationPurpose::SessionRetryAuto
        | ModelInvocationPurpose::SessionRotateChild
        | ModelInvocationPurpose::AgentSpawnChild
        | ModelInvocationPurpose::AgentReserveSuccessor
        | ModelInvocationPurpose::WorkflowGraphNode
        | ModelInvocationPurpose::WorkflowChainIteration
        | ModelInvocationPurpose::RecursiveLiveTask
        | ModelInvocationPurpose::ScheduledFresh
        | ModelInvocationPurpose::AgentScheduleWakeFresh
        | ModelInvocationPurpose::ScheduledResumeWatch
        | ModelInvocationPurpose::IssueTrackerDispatch => {
            ExecutionRoute::Boundaries(SESSION_BOUNDARIES)
        }
        ModelInvocationPurpose::SessionHarnessTurn
        | ModelInvocationPurpose::SessionHarnessCompaction => {
            ExecutionRoute::Boundaries(HARNESS_BOUNDARIES)
        }
        ModelInvocationPurpose::SessionCodexAppServerTurn => {
            ExecutionRoute::Boundaries(&["appserver_model_request"])
        }
        ModelInvocationPurpose::SessionOpenAiCompatibleTurn => {
            ExecutionRoute::Boundaries(&["local_openai_compatible_http"])
        }
        ModelInvocationPurpose::PromptCompile
        | ModelInvocationPurpose::TextGenerateRpc
        | ModelInvocationPurpose::SessionTitle
        | ModelInvocationPurpose::SessionSummary
        | ModelInvocationPurpose::MemoryObservationExtract
        | ModelInvocationPurpose::DreamConsolidation => {
            ExecutionRoute::Boundaries(MEMORY_BOUNDARIES)
        }
        ModelInvocationPurpose::MemoryEmbeddingIndex => {
            ExecutionRoute::Boundaries(EMBEDDING_BOUNDARIES)
        }
        ModelInvocationPurpose::StallClassifier => {
            ExecutionRoute::Boundaries(&["stall_classifier_http"])
        }
        ModelInvocationPurpose::DialecticQuery => ExecutionRoute::Boundaries(&["dialectic_http"]),
        ModelInvocationPurpose::ModelDiscoveryClaudeProbe => {
            ExecutionRoute::Excluded("claude_catalog")
        }
        ModelInvocationPurpose::QueueDeferredModelTask => ExecutionRoute::Excluded("queue_noop"),
    }
}

