pub fn purpose_allows_runtime_route(
    purpose: ModelInvocationPurpose,
    runtime_route: RuntimeExecutionRoute,
) -> bool {
    let ExecutionRoute::Boundaries(ids) = execution_route(purpose) else {
        return false;
    };
    ids.iter().any(|id| {
        EXECUTION_BOUNDARIES
            .iter()
            .any(|contract| contract.id == *id && contract.runtime_route == runtime_route)
    })
}

