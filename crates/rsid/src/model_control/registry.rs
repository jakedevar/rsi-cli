pub fn render_markdown_table() -> String {
    let mut out = String::from(
        "| Purpose ID | Trigger | Owner | Foreground/background | Provider/model resolution | Effort | Authentication/billing path | Current entry point | Backend(s) | Paid risk | Current guard | Budget / attribution target | Concurrency | Cancellation | Persistence/restart | Observability | Current budget enforcement | Dedup / retry | Required admission hook | Accounting hook | Emergency control |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for entry in REGISTRY {
        let row = format!(
            "| `{}` | {} | {} | {} | {} | {} | {} | `{}` | {} | `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            entry.doc_purpose(),
            entry.trigger,
            entry.owner,
            match entry.foreground {
                InvocationForeground::Foreground => "foreground",
                InvocationForeground::Background => "background",
            },
            entry.provider_model_resolution,
            entry.effort,
            entry.auth_billing_path,
            entry.current_entry_point,
            entry.backends,
            match entry.paid_risk {
                PaidRisk::PaidCapable => "paid-capable",
                PaidRisk::LocalOnly => "local-only",
                PaidRisk::CatalogOnly => "catalog-only",
                PaidRisk::NonInvocation => "non-invocation",
            },
            entry.current_guard,
            entry.budget_attribution_target,
            entry.concurrency,
            entry.cancellation,
            entry.persistence_restart,
            entry.observability,
            entry.current_budget_enforcement,
            entry.dedup_retry,
            entry.required_admission_hook,
            entry.accounting_hook,
            entry.emergency_control,
        );
        out.push_str(&row);
    }
    out
}

pub fn render_exclusion_markdown_table() -> String {
    let mut out = String::from(
        "| Contract ID | Source item | Structurally allowed operation |\n| --- | --- | --- |\n",
    );
    for contract in NON_INVOCATIONS {
        out.push_str(&format!(
            "| `{}` | `{}` | {} Proof identity: `{}`. |\n",
            contract.id,
            contract.item,
            contract.allowed_operation.description(),
            contract.proof_ident,
        ));
    }
    out
}

