// Generate src/keymap.generated.ts from the TUI's docs/keybindings.md: the
// generated Normal-mode key table, its reserved sequences and the generated
// command-mode table. The desktop key engine (src/keyengine.ts) is driven by
// this table, so the desktop learns a TUI key as soon as the TUI documents it.
//
//   node scripts/keymap.mjs          # rewrite src/keymap.generated.ts
//   node scripts/keymap.mjs --check  # exit 1 when it is stale
//
// TODO(hub #3003): share the table parser with scripts/parity.mjs (slice 1)
// once both have landed; this module parses only the subset the engine needs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOC_PATH = join(root, '..', 'docs', 'keybindings.md');
export const OUT_PATH = join(root, 'src', 'keymap.generated.ts');

/** The text between `<!-- rsi:generated:begin <name> -->` and its end marker. */
export function generatedBlock(md, name) {
  const begin = `<!-- rsi:generated:begin ${name} -->`;
  const start = md.indexOf(begin);
  if (start < 0) throw new Error(`keybindings.md has no generated block "${name}"`);
  const end = md.indexOf('<!-- rsi:generated:end -->', start);
  if (end < 0) throw new Error(`generated block "${name}" is not closed`);
  return md.slice(start + begin.length, end);
}

/** Split one Markdown table row into trimmed cells; `\|` stays a literal pipe. */
export function tableCells(line) {
  const t = line.trim();
  if (!t.startsWith('|')) return null;
  const cells = [];
  let cur = '';
  for (let i = 1; i < t.length; i++) {
    const c = t[i];
    if (c === '\\' && t[i + 1] === '|') { cur += '|'; i++; continue; }
    if (c === '|') { cells.push(cur.trim()); cur = ''; continue; }
    cur += c;
  }
  if (cur.trim() !== '') cells.push(cur.trim());
  return cells;
}

/** Every table body row (header and separator skipped) in a block, per table. */
function tables(block) {
  const out = [];
  let rows = null;
  for (const line of block.split('\n')) {
    const cells = tableCells(line);
    if (!cells) { rows = null; continue; }
    if (rows === null) { rows = []; out.push({ header: cells, rows }); continue; }
    if (cells.every((c) => /^:?-+:?$/.test(c))) continue;
    rows.push(cells);
  }
  return out;
}

/** The backtick spans of a cell, in order. */
export function codeSpans(cell) {
  return [...cell.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
}

/** Normal-mode rows and reserved sequences from the `normal` block. */
export function parseNormal(md) {
  const ts = tables(generatedBlock(md, 'normal'));
  const keys = ts.find((t) => t.header[0] === 'Keys' && t.header[1] === 'Action');
  const reserved = ts.find((t) => t.header[0] === 'Keys' && t.header[1] === 'Reserved as');
  if (!keys || !reserved) throw new Error('normal block lacks the key or reserved table');
  const seen = new Set();
  const rows = [];
  for (const [k, title = '', description = ''] of keys.rows) {
    const [seq] = codeSpans(k);
    if (!seq || seen.has(seq)) continue;
    seen.add(seq);
    rows.push({ keys: seq, title, description });
  }
  const res = reserved.rows.flatMap(([k, kind = '', why = '']) => {
    const [seq] = codeSpans(k);
    return seq && (kind === 'prefix' || kind === 'no-op') ? [{ keys: seq, kind, why }] : [];
  });
  return { rows, reserved: res };
}

/** `:manager global [arg]` -> { name: 'manager global', arg: 'optional' }. */
export function parseCommandSpelling(spelling) {
  let s = spelling.trim().replace(/^:/, '');
  let arg = 'none';
  const m = s.match(/\s+(\[arg\]|<arg>)$/);
  if (m) {
    arg = m[1] === '<arg>' ? 'required' : 'optional';
    s = s.slice(0, m.index);
  }
  return { name: s, arg };
}

/** Command rows from the `command-mode` block. */
export function parseCommands(md) {
  const ts = tables(generatedBlock(md, 'command-mode'));
  const t = ts.find((x) => x.header[0] === 'Command');
  if (!t) throw new Error('command-mode block lacks the command table');
  const out = [];
  const seen = new Set();
  for (const [cmd, aliases = '', title = '', description = ''] of t.rows) {
    const [spelling] = codeSpans(cmd);
    if (!spelling) continue;
    const { name, arg } = parseCommandSpelling(spelling);
    if (seen.has(name)) continue;
    seen.add(name);
    const al = codeSpans(aliases).map((a) => parseCommandSpelling(a).name).filter((a) => a !== name);
    out.push({ name, aliases: al, arg, title, description });
  }
  return out;
}

const HEADER = `// Generated by desktop/scripts/keymap.mjs from docs/keybindings.md; do not edit.
// Regenerate with \`cd desktop && node scripts/keymap.mjs\` after the TUI's
// keybindings change (npm test fails while this file is stale).
`;

function list(name, type, items) {
  const body = items.map((x) => `  ${JSON.stringify(x)},`).join('\n');
  return `export const ${name}: readonly ${type}[] = [\n${body}\n];\n`;
}

/** The TypeScript source for a keybindings.md text. */
export function renderKeymap(md) {
  const { rows, reserved } = parseNormal(md);
  const commands = parseCommands(md);
  return [
    HEADER,
    'export interface NormalKeyRow { keys: string; title: string; description: string }',
    "export interface ReservedKeyRow { keys: string; kind: 'prefix' | 'no-op'; why: string }",
    "export interface CommandRow { name: string; aliases: string[]; arg: 'none' | 'optional' | 'required'; title: string; description: string }",
    '',
    list('NORMAL_KEYS', 'NormalKeyRow', rows),
    list('RESERVED_KEYS', 'ReservedKeyRow', reserved),
    list('COMMANDS', 'CommandRow', commands),
  ].join('\n');
}

/** True when the committed file matches the current keybindings.md. */
export function keymapIsFresh(docPath = DOC_PATH, outPath = OUT_PATH) {
  let current = '';
  try { current = readFileSync(outPath, 'utf8'); } catch { return false; }
  return current === renderKeymap(readFileSync(docPath, 'utf8'));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    if (!keymapIsFresh()) {
      console.error('src/keymap.generated.ts is stale: run `node scripts/keymap.mjs` in desktop/');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_PATH, renderKeymap(readFileSync(DOC_PATH, 'utf8')));
  }
}
