const emitted = new Set(primitiveNames);
function emit(name) {
  if (emitted.has(name)) return;
  const def = definitions.get(name);
  if (!def) throw Error(`Missing type: ${name}`);
  emitted.add(name);
  for (const token of def.match(/\b\w+V1\b/g) ?? []) if (definitions.has(token)) emit(token);
  output += `export const ${name} = define(${JSON.stringify(name)}, ${def});\nexport type ${name} = Infer<typeof ${name}>;\n`;
}
for (const name of definitions.keys()) emit(name);
output += `export type TypeMap = {${[...definitions.keys()].map(n => `${n}: ${n}`).join('; ')}};\n`;
