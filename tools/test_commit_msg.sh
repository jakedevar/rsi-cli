#!/usr/bin/env bash
# suite-gate: tap
# Exercise the commit-msg hook with real local commits (#2597). Port of the Python suite
# tools/test_commit_msg.py (#366).
#
# Case map (legacy tools/test_commit_msg.py -> here, same order and names): ai_coauthor_trailer_is_stripped,
# generated_with_banner_is_stripped, clean_message_is_untouched, human_coauthor_is_kept,
# human_named_like_an_ai_product_is_kept (all five variants), known_ai_signatures_are_stripped (all six),
# human_kept_while_ai_stripped_in_same_message. Added: the C-locale banner, an unrelated generated line, documentary lines kept and indented banners stripped (#482).
source "$(dirname "$0")/../scripts/tests/lib/tap.sh"

HOOKS="$REPO_ROOT/tools/git-hooks"

setup_repo() {
    REPO="$CASE_DIR/repo"
    mkdir -p "$REPO"
    git -C "$REPO" init -q -b scratch
    git -C "$REPO" config user.name Test
    git -C "$REPO" config user.email test@example.invalid
    git -C "$REPO" config core.hooksPath "$HOOKS"
    printf 'x\n' >"$REPO/f.txt"
    git -C "$REPO" add f.txt
}

# commit <args...>: a real commit through the hooks, without the agent's own environment.
commit() {
    COMMIT_ERR="$(env -u RSI_SKIP_STATIC_GUARDS -u CLAUDE_AGENT_ROLE git -C "$REPO" commit -q "$@" 2>&1 >/dev/null)" \
        || tap_fail "git commit failed: $COMMIT_ERR"
}

body() { # the last commit's message, trimmed
    git -C "$REPO" log -1 --format=%B
}

case_an_ai_coauthor_trailer_is_stripped() {
    setup_repo
    commit -m $'fix: thing\n\nDetails here.\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\nCo-authored-by: Codex <codex@openai.com>'
    assert_eq $'fix: thing\n\nDetails here.' "$(body)" "the message"
    assert_contains "$COMMIT_ERR" "removed AI attribution"
}

case_a_generated_with_banner_is_stripped() {
    setup_repo
    commit -m $'docs: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
    assert_eq "docs: x" "$(body)" "the message"
}

# The emoji is four BYTES in a C/POSIX locale: the banner must be stripped there too (the hook once
# allowed four characters before "generated", so the byte count decided it; found by running this
# suite natively in a job with no UTF-8 locale).
case_a_generated_with_banner_is_stripped_in_the_c_locale() {
    setup_repo
    LC_ALL=C LANG=C commit -m $'docs: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
    assert_eq "docs: x" "$(body)" "the message in the C locale"
}

# An unrelated "generated with" line is ordinary text and is kept.
case_an_unrelated_generated_with_line_is_kept() {
    setup_repo
    local message=$'docs: x\n\nGenerated with rustfmt and sed.'
    commit -m "$message"
    assert_eq "$message" "$(body)" "the message"
}

# #482: the strip is for the banner itself, wherever it is indented, and never for somebody's
# documentary text: a deeply quoted line or a line about a product that merely starts with a name.
case_documentary_lines_that_are_not_the_banner_are_kept() {
    setup_repo
    local line
    for line in \
        '> > > Generated with ClaudeCompat' \
        '> > > Generated with Claude Code' \
        'Generated with ClaudeCompat' \
        'Generated by Codexis tooling'; do
        commit --allow-empty -m $'docs: quote\n\n'"$line"
        assert_eq $'docs: quote\n\n'"$line" "$(body)" "the message keeps [$line]"
    done
}

case_an_indented_or_singly_quoted_banner_is_stripped() {
    setup_repo
    local line
    for line in \
        '         Generated with Codex' \
        $'\t\tGenerated with Claude Code' \
        '    🤖 Generated with [Claude Code](https://claude.com/claude-code)' \
        '> Generated with Claude Code' \
        'Generated by Gemini.'; do
        commit --allow-empty -m $'docs: banner\n\n'"$line"
        assert_eq "docs: banner" "$(body)" "the message after [$line]"
    done
}

case_a_clean_message_is_untouched() {
    setup_repo
    local message=$'feat: plain\n\nBody line.\n\nFixes #1'
    commit -m "$message"
    assert_eq "$message" "$(body)" "the message"
    assert_not_contains "$COMMIT_ERR" "removed AI attribution"
}

case_a_human_coauthor_is_kept() {
    setup_repo
    local message=$'feat: pair\n\nCo-authored-by: Jane Doe <jane@example.invalid>'
    commit -m "$message"
    assert_eq "$message" "$(body)" "the message"
}

# #2600: a name or address merely containing an AI term is not AI attribution.
case_a_human_named_like_an_ai_product_is_kept() {
    setup_repo
    local trailer
    for trailer in \
        "Co-authored-by: Claude Dupont <claude.dupont@example.invalid>" \
        "Co-authored-by: Claude <claude@example.invalid>" \
        "Co-authored-by: Gemma Cursor <gemini.fan@example.invalid>" \
        "Co-authored-by: Pat Devin <pat@gemini-labs.example.invalid>" \
        "Co-authored-by: Sam Codex <sam@bedrock.example.invalid>"; do
        commit --allow-empty -m $'feat: pair\n\n'"$trailer"
        assert_eq $'feat: pair\n\n'"$trailer" "$(body)" "the message with [$trailer]"
    done
}

case_known_ai_signatures_are_stripped() {
    setup_repo
    local trailer
    for trailer in \
        "Co-authored-by: Claude <noreply@anthropic.com>" \
        "Co-authored-by: Claude Code <claude@example.invalid>" \
        "Co-authored-by: Gemini <noreply@google.com>" \
        "Co-authored-by: Cursor Agent <cursoragent@cursor.com>" \
        "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>" \
        "Co-authored-by: aider (gpt-5) <noreply@aider.chat>"; do
        commit --allow-empty -m $'feat: x\n\n'"$trailer"
        assert_eq "feat: x" "$(body)" "the message with [$trailer]"
    done
}

case_a_human_is_kept_while_an_ai_is_stripped_in_the_same_message() {
    setup_repo
    commit -m $'feat: mix\n\nCo-authored-by: Claude Dupont <claude@example.invalid>\nCo-authored-by: Claude <noreply@anthropic.com>'
    assert_eq $'feat: mix\n\nCo-authored-by: Claude Dupont <claude@example.invalid>' "$(body)" "the message"
}

run_case "an AI coauthor trailer is stripped" case_an_ai_coauthor_trailer_is_stripped
run_case "a generated-with banner is stripped" case_a_generated_with_banner_is_stripped
run_case "a generated-with banner is stripped in the C locale" case_a_generated_with_banner_is_stripped_in_the_c_locale
run_case "an unrelated generated-with line is kept" case_an_unrelated_generated_with_line_is_kept
run_case "documentary lines that are not the banner are kept" case_documentary_lines_that_are_not_the_banner_are_kept
run_case "an indented or singly quoted banner is stripped" case_an_indented_or_singly_quoted_banner_is_stripped
run_case "a clean message is untouched" case_a_clean_message_is_untouched
run_case "a human coauthor is kept" case_a_human_coauthor_is_kept
run_case "a human named like an AI product is kept" case_a_human_named_like_an_ai_product_is_kept
run_case "known AI signatures are stripped" case_known_ai_signatures_are_stripped
run_case "a human is kept while an AI is stripped in the same message" case_a_human_is_kept_while_an_ai_is_stripped_in_the_same_message
tap_done
