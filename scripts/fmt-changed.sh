#!/usr/bin/env bash
# Format only the Rust files this change touched (AGENTS.md rule 6).
#
# usage: scripts/fmt-changed.sh [BASE]
#   no BASE: the .rs files that differ from HEAD (staged or not), plus untracked
#   BASE:    the .rs files that differ between merge-base(BASE, HEAD) and the
#            working tree, plus untracked files
#            (for example an integration worktree: scripts/fmt-changed.sh origin/rolling)
#
# rustfmt also rewrites every out-of-line child module (`mod foo;`) of a file
# it is given, and `skip_children` is nightly-only, so a file the formatter
# rewrote that was clean before and is not part of the change is restored
# from the index afterwards (#1121). Prints the files it formatted.
#
# Generated files are skipped, and each skip is reported on stderr: a file named
# `*.generated.rs`, or one whose first lines carry a `GENERATED by` / `@generated`
# marker. The generator owns their format, and some are `include!` fragments (for
# example `tauri::generate_handler![...]`) that are not items, so rustfmt cannot
# parse them and the whole run would exit non-zero (#76). Skipping in the script
# rather than reshaping the generator keeps the fragment valid for its expression
# `include!` site and covers every present and future generated file.
set -euo pipefail

base=${1:-HEAD}
top=$(git rev-parse --show-toplevel)
cd "$top"
base=$(git merge-base "$base" HEAD)

# Plain arrays and newline lists only: macOS ships bash 3.2, which has no
# `mapfile` and no associative arrays (#1229).
changed=()
while IFS= read -r file; do
    [ -n "$file" ] && changed+=("$file")
done < <(
    {
        git diff --name-only --diff-filter=d "$base" -- '*.rs'
        git ls-files --others --exclude-standard -- '*.rs'
    } | sort -u
)

is_generated() {
    case "$1" in
        *.generated.rs) return 0 ;;
    esac
    [ -f "$1" ] && head -n 10 -- "$1" | grep -Eq 'GENERATED by|@generated'
}

# Keep the skipped generated paths out of the formatter's argument list.
formattable=()
if [ "${#changed[@]}" -gt 0 ]; then
    # bash32-safe: guarded by the length check above
    for file in "${changed[@]}"; do
        if is_generated "$file"; then
            printf 'fmt-changed: skipped generated file %s\n' "$file" >&2
        else
            formattable+=("$file")
        fi
    done
fi
if [ "${#formattable[@]}" -eq 0 ]; then
    exit 0
fi
# bash32-safe: formattable is non-empty past the exit above
changed=("${formattable[@]}")

# bash32-safe: changed is non-empty past the exit above
in_change=$(printf '%s\n' "${changed[@]}")
dirty_before=$(git diff --name-only)
listed() {
    # Exact whole-line match of $1 in the newline list $2.
    [ -n "$2" ] && printf '%s\n' "$2" | grep -Fxq -- "$1"
}

# bash32-safe: changed is non-empty
rustfmt --edition 2024 "${changed[@]}"

while IFS= read -r file; do
    [ -n "$file" ] || continue
    if ! listed "$file" "$in_change" && ! listed "$file" "$dirty_before"; then
        git checkout --quiet -- "$file"
    fi
done < <(git diff --name-only)

# bash32-safe: changed is non-empty
printf '%s\n' "${changed[@]}"
